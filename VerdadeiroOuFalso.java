public class VerdadeiroOuFalso {
    public static void main(String[] args) {
        boolean var1 = true;
        boolean var2 = false;
        boolean var3 = true;

        if (var1) {
            System.out.println("Variável 1 é verdadeira");
        } else {
            System.out.println("Variável 1 é falsa");
        }

        if (var2) {
            System.out.println("Variável 2 é verdadeira");
        } else {
            System.out.println("Variável 2 é falsa");
        }

        if (var3) {
            System.out.println("Variável 3 é verdadeira");
        } else {
            System.out.println("Variável 3 é falsa");
        }
    }
}
